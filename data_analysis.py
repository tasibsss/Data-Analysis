# ────────────────────────────────────────────────────────────
# STEP 1 — VADER Sentiment (compound score, -1 to +1)
# ────────────────────────────────────────────────────────────
print("\n📌 STEP 1 — Running VADER on titles …")
analyzer = SentimentIntensityAnalyzer()

def vader_scores(text):
    s = analyzer.polarity_scores(str(text))
    return s["neg"], s["neu"], s["pos"], s["compound"]

df[["VADER_neg", "VADER_neu", "VADER_pos", "VADER_compound"]] = df["Title"].apply(
    lambda t: pd.Series(vader_scores(t))
)

# Classify: compound >= 0.05 → Positive, <= -0.05 → Negative, else Neutral
def vader_label(compound):
    if compound >= 0.05:
        return "Positive"
    elif compound <= -0.05:
        return "Negative"
    return "Neutral"

df["VADER_Sentiment"] = df["VADER_compound"].apply(vader_label)
print(df["VADER_Sentiment"].value_counts())

# ────────────────────────────────────────────────────────────
# STEP 2 — TextBlob Sentiment (polarity -1 to +1, subjectivity 0 to 1)
# ────────────────────────────────────────────────────────────
print("\n📌 STEP 2 — Running TextBlob on titles …")

def textblob_scores(text):
    blob = TextBlob(str(text))
    return blob.sentiment.polarity, blob.sentiment.subjectivity

df[["TB_polarity", "TB_subjectivity"]] = df["Title"].apply(
    lambda t: pd.Series(textblob_scores(t))
)

def textblob_label(polarity):
    if polarity > 0.05:
        return "Positive"
    elif polarity < -0.05:
        return "Negative"
    return "Neutral"

df["TB_Sentiment"] = df["TB_polarity"].apply(textblob_label)
print(df["TB_Sentiment"].value_counts())

# ────────────────────────────────────────────────────────────
# STEP 3 — Agreement between the two models
# ────────────────────────────────────────────────────────────
print("\n📌 STEP 3 — Model Agreement")
df["Models_Agree"] = df["VADER_Sentiment"] == df["TB_Sentiment"]
agree_pct = df["Models_Agree"].mean() * 100
print(f"   Models agree on {agree_pct:.1f}% of titles")

# ────────────────────────────────────────────────────────────
# STEP 4 — Sentiment vs Star Rating
# ────────────────────────────────────────────────────────────
print("\n📌 STEP 4 — VADER Compound Score by Star Rating")
avg_sentiment = df.groupby("Rating (1-5)")["VADER_compound"].mean().round(3)
print(avg_sentiment)

