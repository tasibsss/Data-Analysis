# STEP 5 — Hypothesis Testing
# ────────────────────────────────────────────────────────────
print("\n📌 STEP 5 — Hypothesis Testing")
# H0: No difference in mean price across rating groups
groups = [df[df["Rating (1-5)"] == r]["Price (£)"].values
          for r in sorted(df["Rating (1-5)"].unique())]
f_stat, p_value = stats.f_oneway(*groups)
print(f"   One-way ANOVA — Price vs Rating:")
print(f"   F-statistic = {f_stat:.4f},  p-value = {p_value:.4f}")
if p_value < 0.05:
    print("   ✅ Significant: price differs across rating groups (p < 0.05)")
else:
    print("   ❌ Not significant: no strong price-rating relationship (p ≥ 0.05)")

